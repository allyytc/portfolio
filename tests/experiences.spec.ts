const evidence = 'docs/portfolio/evidence/phase7b/regression'
async function capture(page: Page, name: string) {
  await page.screenshot({path:`${evidence}/${name}.png`,fullPage:true})
  await writeFile(`${evidence}/${name}.json`, JSON.stringify(await page.evaluate(()=>({camera:window.__studioCamera,metrics:window.__studioMetrics})),null,2))
}
async function load(page: Page) {
  await page.goto('/')
  await page.waitForFunction(() => (window.__studioMetrics?.triangles ?? 0) > 10000 && !window.__studioCamera?.transitioning)
}
async function hit(page: Page, world: number[]) {
  const rect = (await page.locator('canvas').boundingBox())!
  const pose = await page.evaluate(() => window.__studioCamera!)
  const camera = new OrthographicCamera(-rect.width/2,rect.width/2,rect.height/2,-rect.height/2,.1,60)
  camera.position.fromArray(pose.position);camera.lookAt(new Vector3().fromArray(pose.target));camera.zoom=pose.zoom;camera.updateProjectionMatrix();camera.updateMatrixWorld()
  const point = new Vector3().fromArray(world).project(camera)
  await page.mouse.click(rect.x+(point.x+1)*rect.width/2,rect.y+(1-point.y)*rect.height/2)
}
async function bounds() { return JSON.parse(await readFile('src/studio/sceneBounds.json','utf8')).nodes }

